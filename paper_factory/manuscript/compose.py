"""P16–P20: deterministic manuscript composition.

Origin policy: these sections are generated by Paper Factory code from the
claim graph, metrics and evidence ledger — template prose with macro-filled
numbers. Backend identity = {"family": "deterministic"}; marking n/a. The
firewall is consulted before every write; origin receipts are recorded.
An optional LLM polish layer may replace sections later — only through the
provider router under the same policy.
"""
